/** So'rovdan tilni aniqlaydi (query > cookie > default uz) */
export function pickLang(req) {
  const q = String(req.query?.lang || "");
  if (I18N[q]) return q;
  const m = (req.headers.cookie || "").match(/(?:^|;\s*)lang=([a-z]{2})/);
  if (m && I18N[m[1]]) return m[1];
  return "uz";
}

export function t(lang) {
  return I18N[lang] || I18N.uz;
}

